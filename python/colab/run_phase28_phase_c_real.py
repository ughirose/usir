    ap = argparse.ArgumentParser(description="Phase 28.2 Phase C real-model measurement")
    ap.add_argument("--model-id", default=model_id or DEFAULT_MODEL_ID)
    ap.add_argument("--dtype", default="bf16", choices=["bf16", "fp16", "fp32"])

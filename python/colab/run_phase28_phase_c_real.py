def calibrate_steerer(model: Any, tok: Any, cfg: Cfg, log: Callable[[str], None]) -> Dict[str, Any]:
    hf_cfg = model.config
    d_model = int(hf_cfg.hidden_size)
    n_layers = int(hf_cfg.num_hidden_layers)
    st = SymplecticActivationSteerer(d_model=d_model, num_layers=n_layers, layer_ratio=cfg.steer_layer_ratio)
    texts = [c["text"] for c in CORPUS]
    hs: List[np.ndarray] = []
    for t in texts:
        enc = tok(t, return_tensors="pt").to(cfg.device)
        with torch.no_grad():
            out = model(**enc, output_hidden_states=True)
        # hidden_states[0] is the embedding output, so the output of decoder layer `layer_idx` (where the hook sits)
        # is hidden_states[layer_idx + 1]. Position 0 is excluded (attention-sink token has outlier norm).
        h = out.hidden_states[st.layer_idx + 1][0].float()
        h = h[1:] if h.shape[0] > 1 else h
        hs.append(h.mean(dim=0).cpu().numpy())
    v = st.calibrate_12_element_axes(hidden_states_list=hs, corpus=texts, axis_mode="qr")  # Phase 28 behaviour (Phase 33 uses independent axes)
    hc = np.stack(hs) - np.mean(hs, axis=0, keepdims=True)
    sv = np.linalg.svd(hc, compute_uv=False)
    info = {
        "d_model": d_model, "num_layers": n_layers, "layer_idx": st.layer_idx, "n_calibration_texts": len(texts),
        "orthonormality": st.verify_orthonormality(),
        "centered_H_singular_values_top12": [float(x) for x in sv[:12]],
        "centered_H_rank_gt_1e-6_rel": int((sv > 1e-6 * sv[0]).sum()),
        "note": "V_steer columns come from QR of the ridge solution; columns beyond the first mix the earlier axes.",
    }
    log(f"[steer] calibrated layer={st.layer_idx} rank={info['centered_H_rank_gt_1e-6_rel']} ortho={info['orthonormality']['is_orthonormal']}")
    return {"steerer": st, "info": info}


def run_steering_stage(model: Any, tok: Any, cfg: Cfg, prompts: Sequence[str], base_stage: Dict[str, Any],
                       log: Callable[[str], None], checks: Dict[str, Any]) -> Dict[str, Any]:
    cal = calibrate_steerer(model, tok, cfg, log)
    st: SymplecticActivationSteerer = cal["steerer"]
    base_q = base_stage["summary"].get("q_mean")
    if base_q is None:
        raise RuntimeError("no successful base generations: cannot define delta_q")
    target_q = np.mean([extract_usir_24d(c["text"])["q"] for c in CORPUS if c["phase"] in ("II_Critical", "III_Void")], axis=0)
    dq = (np.asarray(target_q, dtype=float) - np.asarray(base_q, dtype=float)).astype(np.float32)
    stage: Dict[str, Any] = {
        "calibration": cal["info"],
        "delta_q": {"value": [float(x) for x in dq], "norm": float(np.linalg.norm(dq)),
                    "definition": "mean q of CORPUS chunks with phase in {II_Critical, III_Void} minus mean q of stage (a) generations",
                    "target_q": [float(x) for x in target_q], "base_q": [float(x) for x in base_q]},
        "conditions": {},
    }
    # integrity check: the hook changes logits and is fully removed afterwards
    probe = prompts[0]
    l0 = _probe_logits(model, tok, probe, cfg)
    with st.steering_context(dq, cfg.alphas[min(1, len(cfg.alphas) - 1)], model=model):
        l1 = _probe_logits(model, tok, probe, cfg)
    l2 = _probe_logits(model, tok, probe, cfg)
    checks["steer_hook_max_abs_logit_change"] = float((l1 - l0).abs().max())
    checks["steer_hook_removed_max_abs_logit_diff"] = float((l2 - l0).abs().max())

    for a in cfg.alphas:
        name = f"steer_alpha_{a:g}"
        stage["conditions"][name] = run_condition(
            name, model, tok, prompts, cfg, log, ctx_factory=lambda a=a: st.steering_context(dq, a, model=model))
        stage["conditions"][name]["paired_vs_base"] = paired_vs_base(stage["conditions"][name]["records"], base_stage["records"])
        stage["conditions"][name]["alpha_act"] = float(a)
    if cfg.steer_control:
        a_ctl = float(cfg.alphas[min(1, len(cfg.alphas) - 1)])
        rnd = SymplecticActivationSteerer(d_model=st.d_model, num_layers=st.num_layers, layer_ratio=cfg.steer_layer_ratio)  # random Haar V (seed 42)
        name = f"steer_random_direction_alpha_{a_ctl:g}"
        stage["conditions"][name] = run_condition(
            name, model, tok, prompts, cfg, log, ctx_factory=lambda: rnd.steering_context(dq, a_ctl, model=model))
        stage["conditions"][name]["paired_vs_base"] = paired_vs_base(stage["conditions"][name]["records"], base_stage["records"])
        stage["conditions"][name]["alpha_act"] = a_ctl
    a_lat = float(cfg.alphas[min(1, len(cfg.alphas) - 1)])
    stage["latency"] = latency_bench(
        model, tok, prompts[0],
        {"base": contextlib.nullcontext, f"steer_alpha_{a_lat:g}": lambda: st.steering_context(dq, a_lat, model=model)}, cfg, log)
    return stage


# ----- GRPO-LoRA ---------------------------------------------------------------

class LoraStateSwitcher:
    """Switches the model between original / unmerged-LoRA / merged-LoRA without reloading.

    original : wrapper removed, base weight restored from a clone (exactly the pre-training model).
    unmerged : AttachedLoRALinear wrapper in place (extra low-rank matmuls at every forward).
    merged   : wrapper removed, base weight = W + scaling * B @ A (no extra compute).
    """

    def __init__(self, model: Any):
        self.entries: List[Any] = []
        for name, mod in list(model.named_modules()):
            if isinstance(mod, AttachedLoRALinear):
                parts = name.split(".")
                parent = model.get_submodule(".".join(parts[:-1])) if len(parts) > 1 else model
                w = mod.base_layer.weight
                self.entries.append((parent, parts[-1], mod, w.detach().clone()))
        self.state = "unmerged"

    def _merged_weight(self, mod: Any, orig: Any) -> Any:
        delta = (mod.lora_B.detach().float() @ mod.lora_A.detach().float()) * mod.scaling
        return (orig.float() + delta).to(orig.dtype)

    def set(self, state: str) -> None:
        with torch.no_grad():
            for parent, attr, mod, orig in self.entries:
                if state == "unmerged":
                    mod.base_layer.weight.data.copy_(orig)
                    setattr(parent, attr, mod)
                elif state == "original":
                    mod.base_layer.weight.data.copy_(orig)
                    setattr(parent, attr, mod.base_layer)
                elif state == "merged":
                    mod.base_layer.weight.data.copy_(self._merged_weight(mod, orig))
                    setattr(parent, attr, mod.base_layer)
                else:
                    raise ValueError(state)
        self.state = state

    @contextlib.contextmanager
    def ctx(self, state: str):
        self.set(state)
        yield


def run_grpo_stage(model: Any, tok: Any, cfg: Cfg, prompts: Sequence[str], base_stage: Dict[str, Any],
                   probe_logits_base: Any, log: Callable[[str], None], checks: Dict[str, Any]) -> Dict[str, Any]:
    for p in model.parameters():
        p.requires_grad_(False)
    info = attach_lora_to_model(model, target_modules=("q_proj", "v_proj"), r=cfg.lora_r, alpha=cfg.lora_alpha)
    n_trainable = int(sum(p.numel() for p in model.parameters() if p.requires_grad))
    if n_trainable != int(info["total_lora_params"]) or info["num_attached"] == 0:
        raise RuntimeError(f"trainable params {n_trainable} != LoRA params {info['total_lora_params']} (attached={info['num_attached']})")
    model.eval()
    if cfg.device.startswith("cuda"):
        torch.cuda.reset_peak_memory_stats()
    torch.manual_seed(cfg.seed)
    t0 = time.perf_counter()
    res = run_authentic_grpo_lora_forge(
        model, tokenizer=tok, prompts=list(TRAIN_PROMPTS), num_rollouts=cfg.grpo_rollouts, beta_kl=cfg.grpo_beta_kl,
        learning_rate=cfg.grpo_lr, num_steps=cfg.grpo_steps, device=cfg.device, domain="novel",
        max_new_tokens=cfg.grpo_max_new_tokens, batched_rollouts=True, per_rollout_backward=True,
        prompts_per_step=cfg.grpo_prompts_per_step,
        progress_fn=lambda e: log(f"[grpo] step {e['step']}/{cfg.grpo_steps} reward={e['mean_reward']:.4f} kl={e['mean_kl']:.5f} loss={e['loss']:.5f} {e['sec']:.1f}s"))
    train_wall = time.perf_counter() - t0
    if res.get("mode") != "authentic_pytorch":
        raise RuntimeError(f"GRPO ran in mode {res.get('mode')!r}, not authentic_pytorch")
    stage: Dict[str, Any] = {
        "lora": {k: info[k] for k in ("num_attached", "total_lora_params", "r", "alpha")},
        "trainable_params": n_trainable,
        "train_prompts": list(TRAIN_PROMPTS),
        "train": {"result": res, "wall_sec": train_wall,
                  "peak_cuda_mem_gb": (torch.cuda.max_memory_allocated() / 2 ** 30) if cfg.device.startswith("cuda") else None},
    }
    # logit-level integrity checks
    sw = LoraStateSwitcher(model)
    probe = prompts[0]
    sw.set("unmerged"); l_un = _probe_logits(model, tok, probe, cfg)
    sw.set("merged"); l_me = _probe_logits(model, tok, probe, cfg)
    sw.set("original"); l_or = _probe_logits(model, tok, probe, cfg)
    checks["lora_merged_vs_unmerged_max_abs_logit_diff"] = float((l_me - l_un).abs().max())
    checks["lora_original_vs_pretraining_max_abs_logit_diff"] = float((l_or - probe_logits_base).abs().max())
    checks["lora_effect_merged_vs_original_max_abs_logit_diff"] = float((l_me - l_or).abs().max())
    lp_or = torch.log_softmax(l_or, -1); lp_me = torch.log_softmax(l_me, -1)
    checks["lora_effect_kl_original_to_merged_probe_last_token"] = float((lp_or.exp() * (lp_or - lp_me)).sum())

    if cfg.also_unmerged_gen:
        sw.set("unmerged")
        stage["lora_unmerged"] = run_condition("lora_unmerged", model, tok, prompts, cfg, log)
        stage["lora_unmerged"]["paired_vs_base"] = paired_vs_base(stage["lora_unmerged"]["records"], base_stage["records"])
    sw.set("merged")
    stage["lora_merged"] = run_condition("lora_merged", model, tok, prompts, cfg, log)
    stage["lora_merged"]["paired_vs_base"] = paired_vs_base(stage["lora_merged"]["records"], base_stage["records"])
    stage["latency"] = latency_bench(
        model, tok, prompts[0],
        {"original": lambda: sw.ctx("original"), "lora_unmerged": lambda: sw.ctx("unmerged"), "lora_merged": lambda: sw.ctx("merged")},
        cfg, log)
    sw.set("original")
    return stage



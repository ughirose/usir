def summarize(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    ok = [r for r in records if r.get("error") is None]
    out: Dict[str, Any] = {"n_total": len(records), "n_ok": len(ok), "n_errors": len(records) - len(ok)}
    for k in GEN_KEYS:
        out[k] = _stats([r.get(k) for r in ok])
    for k in SCALAR_KEYS:
        out[k] = _stats([r["metrics"][k] for r in ok])
    k_dead = sum(1 for r in ok if r["metrics"]["in_deadzone"])
    out["deadzone"] = {"count": k_dead, "n": len(ok), "rate": (k_dead / len(ok)) if ok else None,
                       "wilson95": wilson_interval(k_dead, len(ok))}
    regimes: Dict[str, int] = {}
    for r in ok:
        regimes[r["metrics"]["phase_regime"]] = regimes.get(r["metrics"]["phase_regime"], 0) + 1
    out["phase_regime_counts"] = regimes
    out["n_short_lt_40_chars"] = sum(1 for r in ok if r["metrics"]["n_chars"] < 40)
    out["n_grpo_rejected"] = sum(1 for r in ok if r["metrics"]["grpo_rejected"])
    if ok:
        out["q_mean"] = [float(v) for v in np.mean([r["metrics"]["q"] for r in ok], axis=0)]
    else:
        out["q_mean"] = None
    return out


def paired_vs_base(cond: List[Dict[str, Any]], base: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Per-prompt paired differences (condition - base) for prompts that succeeded in both."""
    bmap = {r["prompt_idx"]: r for r in base if r.get("error") is None}
    pairs = [(bmap[r["prompt_idx"]], r) for r in cond if r.get("error") is None and r["prompt_idx"] in bmap]
    res: Dict[str, Any] = {"n_pairs": len(pairs)}
    getters = {k: (lambda r, k=k: r["metrics"][k]) for k in ("len_cv", "sigma_norm", "d_3phase", "grpo_reward_no_ppl",
                                                              "distinct_char_bigram", "cadence_alive")}
    getters["ms_per_token"] = lambda r: r["ms_per_token"]
    getters["in_deadzone"] = lambda r: 1.0 if r["metrics"]["in_deadzone"] else 0.0
    for k, g in getters.items():
        d = np.asarray([g(c) - g(b) for b, c in pairs if g(b) is not None and g(c) is not None], dtype=float)
        res[k] = {
            "mean_diff": float(d.mean()) if d.size else None,
            "std_diff": float(d.std(ddof=1)) if d.size > 1 else None,
            "n_pos": int((d > 0).sum()), "n_neg": int((d < 0).sum()), "n_zero": int((d == 0).sum()),
        }
    return res


def _sanitize(obj: Any) -> Any:
    if isinstance(obj, dict):
        return {str(k): _sanitize(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_sanitize(v) for v in obj]
    if isinstance(obj, np.ndarray):
        return _sanitize(obj.tolist())
    if isinstance(obj, (np.floating, float)):
        f = float(obj)
        return f if math.isfinite(f) else None
    if isinstance(obj, np.integer):
        return int(obj)
    if isinstance(obj, np.bool_):
        return bool(obj)
    return obj


def build_archive_line(result: Dict[str, Any]) -> str:
    """'ARCHIVE_B64 <crc32 hex> <base64(gzip(json))>' as collected by scripts/run_colab_file.py."""
    raw = json.dumps(_sanitize(result), ensure_ascii=False, default=float).encode("utf-8")
    return "ARCHIVE_B64 " + format(zlib.crc32(raw) & 0xFFFFFFFF, "08x") + " " + base64.b64encode(gzip.compress(raw, 9)).decode()


def decode_archive_line(line: str) -> Dict[str, Any]:
    _, crc, b64 = line.strip().split(" ", 2)
    raw = gzip.decompress(base64.b64decode(b64))
    if format(zlib.crc32(raw) & 0xFFFFFFFF, "08x") != crc:
        raise ValueError("crc mismatch")
    return json.loads(raw.decode("utf-8"))



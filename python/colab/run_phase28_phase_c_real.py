def run_all(model: Any, tok: Any, cfg: Cfg, log: Callable[[str], None] = print) -> Dict[str, Any]:
    t_all = time.perf_counter()
    prompts = EVAL_PROMPTS[: max(1, min(cfg.n_prompts, len(EVAL_PROMPTS)))]
    result: Dict[str, Any] = {
        "schema": SCHEMA,
        "timestamp_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "model_id": cfg.model_id,
        "config": cfg.as_dict(),
        "provenance": {
            "mock_used": False,
            "thresholds_defined_by_driver": None,
            "deadzone_definition": "usir_py.manifold_geodesic.compute_three_phase_qda_distance(domain='novel').phase_regime == 'Phase_I_Deadzone'",
            "generation_input": "raw-text continuation (no chat template), sampled with per-prompt seeds shared across conditions",
        },
        "env": {
            "torch": getattr(torch, "__version__", None),
            "cuda_available": bool(torch.cuda.is_available()),
            "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None,
            "param_count": int(sum(p.numel() for p in model.parameters())),
            "dtype": str(next(model.parameters()).dtype),
        },
        "eval_prompts": prompts,
        "stages": {},
        "checks": {},
        "errors": [],
    }
    try:
        import transformers
        result["env"]["transformers"] = transformers.__version__
    except Exception:
        pass
    checks = result["checks"]

    def record_error(stage: str, exc: BaseException) -> None:
        result["errors"].append({"stage": stage, "error": repr(exc), "traceback": traceback.format_exc()[-3000:]})
        log(f"[ERROR] stage {stage}: {exc!r}")
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    probe_base = None
    base_stage: Optional[Dict[str, Any]] = None
    try:
        model.eval()
        probe_base = _probe_logits(model, tok, prompts[0], cfg)
        base_stage = run_condition("base", model, tok, prompts, cfg, log)
        result["stages"]["base"] = base_stage
    except Exception as exc:
        record_error("base", exc)

    if cfg.do_steer and base_stage is not None:
        try:
            result["stages"]["steering"] = run_steering_stage(model, tok, cfg, prompts, base_stage, log, checks)
        except Exception as exc:
            record_error("steering", exc)

    if cfg.do_grpo and base_stage is not None and probe_base is not None:
        try:
            result["stages"]["grpo_lora"] = run_grpo_stage(model, tok, cfg, prompts, base_stage, probe_base, log, checks)
        except Exception as exc:
            record_error("grpo_lora", exc)

    result["total_wall_sec"] = time.perf_counter() - t_all
    return result


def load_model(model_id: str, dtype: str, device: str):
    from transformers import AutoModelForCausalLM, AutoTokenizer
    tdt = {"bf16": torch.bfloat16, "fp16": torch.float16, "fp32": torch.float32}[dtype]
    tok = AutoTokenizer.from_pretrained(model_id)
    try:
        model = AutoModelForCausalLM.from_pretrained(model_id, dtype=tdt)
    except TypeError:
        model = AutoModelForCausalLM.from_pretrained(model_id, torch_dtype=tdt)
    model.to(device)
    model.eval()
    return model, tok



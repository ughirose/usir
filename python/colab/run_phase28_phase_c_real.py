"""Phase 28.2 Phase C: real-model measurement of activation steering and GRPO-LoRA (Colab, single GPU).

This driver replaces the mock-based python/colab/run_experiment_c_lora_forge.py for any claim about a real model.
Every number written to the result JSON is computed from model outputs or from wall-clock timers around
model.generate; nothing is read from a constant or generated by a random-number model of the expected result.
Design constraints:
  * No pass/fail thresholds are defined here. The script reports raw per-prompt values and summary statistics only.
  * A stage that raises is recorded in result["errors"] and the script continues with the next stage; failed values
    are never replaced by defaults.
  * The Deadzone label is the repository classifier usir_py.manifold_geodesic.compute_three_phase_qda_distance
    (regime "Phase_I_Deadzone": ||p||_2 below the domain sigma_crit_low), not a driver-local rule.

Stages
  (a) base      : N prompts, raw-text continuation (no chat template), sampled, per-generate timers.
  (b) steering  : SymplecticActivationSteerer at layer floor(0.65 * L). V_steer is calibrated from the model's own
                  hidden states on the repository corpus (usir_py.corpus_40_benchmark.CORPUS); Delta q* is the
                  measured mean q of non-Deadzone corpus chunks (II_Critical, III_Void) minus the measured mean q
                  of the stage (a) generations. Runs an alpha sweep and a random-direction control.
  (c) GRPO-LoRA : run_authentic_grpo_lora_forge (real rollouts, real rewards, real backward) on training prompts
                  that are disjoint from the evaluation prompts, then generation with the LoRA merged into the
                  base weights, plus an interleaved fixed-token latency benchmark of original / unmerged / merged.
Latency
  per-generate wall time with torch.cuda.synchronize() before and after; ms/token = wall / generated tokens.
  A separate fixed-token greedy benchmark (min_new_tokens = max_new_tokens) interleaves the compared states
  over several repetitions so that clock/thermal drift is spread over all states.

Usage (Colab, after unpacking python/ into sys.path):
    python run_phase28_phase_c_real.py --model-id Qwen/Qwen2.5-3B-Instruct --out result.json
"""


def _sentence_split(text: str) -> List[str]:
    return [s for s in re.split(r"[。！？!?\n]+", text) if s.strip()]


def text_metrics(text: str, prompt: str) -> Dict[str, Any]:
    """Repository metrics for one generated text. Uses the repository extractor / QDA classifier / GRPO reward."""
    feats = extract_usir_24d(text)
    qda = compute_three_phase_qda_distance(text, domain="novel")
    rew = compute_multiplicative_grpo_reward(text, x_0=prompt, domain="novel")
    body = re.sub(r"[\s、。！？!?「」『』（）()]", "", text)
    bigrams = [body[i:i + 2] for i in range(len(body) - 1)]
    op = feats["order_params"]
    return {
        "n_chars": len(text),
        "n_sentences": len(_sentence_split(text)),
        "len_cv": float(feats["len_cv"]),          # CV_L = sigma_L / mu_L of sentence lengths (extractor definition)
        "cadence_alive": float(feats["cadence_alive"]),
        "psi_order": float(op["psi_order"]),
        "phi_void": float(op["phi_void"]),
        "kappa_kin": float(op["kappa_kin"]),
        "sigma_norm": float(qda["sigma_norm"]),    # ||p||_2, compared against sigma_crit_low by the classifier
        "d_3phase": float(qda["d_3phase"]),
        "phase_regime": qda["phase_regime"],
        "in_deadzone": bool(qda["phase_regime"] == DEADZONE_REGIME),
        "grpo_reward_no_ppl": float(rew["reward"]),
        "grpo_m_syntax": float(rew["m_syntax"]),
        "grpo_m_geodesic": float(rew["m_geodesic"]),
        "grpo_m_bridge": float(rew["m_bridge"]),
        "grpo_rejected": bool(rew["is_rejected"]),
        "distinct_char_bigram": (len(set(bigrams)) / len(bigrams)) if bigrams else 0.0,
        "q": [float(v) for v in np.asarray(feats["q"], dtype=float).ravel()],
        "p": [float(v) for v in np.asarray(feats["p"], dtype=float).ravel()],
    }


def wilson_interval(k: int, n: int, z: float = 1.96) -> Optional[List[float]]:
    if n <= 0:
        return None
    ph = k / n
    den = 1.0 + z * z / n
    centre = (ph + z * z / (2 * n)) / den
    half = z * math.sqrt(ph * (1 - ph) / n + z * z / (4 * n * n)) / den
    return [max(0.0, centre - half), min(1.0, centre + half)]


def _stats(vals: Sequence[float]) -> Dict[str, Any]:
    a = np.asarray([v for v in vals if v is not None and np.isfinite(v)], dtype=float)
    if a.size == 0:
        return {"n": 0, "mean": None, "std": None, "median": None, "min": None, "max": None}
    return {
        "n": int(a.size), "mean": float(a.mean()), "std": float(a.std(ddof=1)) if a.size > 1 else 0.0,
        "median": float(np.median(a)), "min": float(a.min()), "max": float(a.max()),
    }



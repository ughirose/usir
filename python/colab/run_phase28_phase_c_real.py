def _sync() -> None:
    if TORCH_AVAILABLE and torch.cuda.is_available():
        torch.cuda.synchronize()


def timed_generate(model: Any, tok: Any, prompt: str, cfg: Cfg, seed: int, *, max_new_tokens: Optional[int] = None,
                   greedy: bool = False, force_tokens: bool = False) -> Dict[str, Any]:
    """One generate() call bracketed by cuda synchronize timers. Returns text of generated tokens only."""
    enc = tok(prompt, return_tensors="pt").to(cfg.device)
    plen = int(enc["input_ids"].shape[1])
    n_new = int(max_new_tokens if max_new_tokens is not None else cfg.max_new_tokens)
    kw: Dict[str, Any] = dict(max_new_tokens=n_new, pad_token_id=(tok.pad_token_id if tok.pad_token_id is not None else tok.eos_token_id))
    if greedy:
        kw["do_sample"] = False
    else:
        kw.update(do_sample=True, temperature=cfg.temperature, top_p=cfg.top_p)
    if force_tokens:
        kw["min_new_tokens"] = n_new
    torch.manual_seed(int(seed))
    _sync()
    t0 = time.perf_counter()
    with torch.no_grad():
        out = model.generate(**enc, **kw)
    _sync()
    wall_ms = (time.perf_counter() - t0) * 1000.0
    new_ids = out[0, plen:]
    n_tok = int(new_ids.numel())
    return {
        "text": tok.decode(new_ids, skip_special_tokens=True),
        "n_new_tokens": n_tok,
        "wall_ms": wall_ms,
        "ms_per_token": (wall_ms / n_tok) if n_tok > 0 else None,
    }


def run_condition(name: str, model: Any, tok: Any, prompts: Sequence[str], cfg: Cfg, log: Callable[[str], None],
                  ctx_factory: Optional[Callable[[], Any]] = None) -> Dict[str, Any]:
    """Generates for each prompt (same per-prompt seeds in every condition) and computes repository metrics."""
    factory = ctx_factory or contextlib.nullcontext
    records: List[Dict[str, Any]] = []
    # untimed warm-up (kernel autotune / allocator / hook first call), not included in any statistic
    try:
        with factory():
            timed_generate(model, tok, prompts[0], cfg, seed=0, max_new_tokens=min(16, cfg.max_new_tokens))
    except Exception as exc:  # recorded, not hidden
        log(f"[{name}] warm-up failed: {exc!r}")
    for i, prompt in enumerate(prompts):
        rec: Dict[str, Any] = {"prompt_idx": i, "prompt": prompt, "seed": cfg.seed + i, "error": None}
        try:
            with factory():
                g = timed_generate(model, tok, prompt, cfg, seed=cfg.seed + i)
            rec.update(g)
            rec["metrics"] = text_metrics(g["text"], prompt)
        except Exception as exc:
            rec["error"] = repr(exc)
            rec["traceback"] = traceback.format_exc()[-1500:]
            if TORCH_AVAILABLE and torch.cuda.is_available():
                torch.cuda.empty_cache()
        records.append(rec)
        if rec["error"] is None:
            log(f"[{name}] {i + 1}/{len(prompts)} tok={rec['n_new_tokens']} {rec['ms_per_token']:.2f}ms/tok "
                f"cv_l={rec['metrics']['len_cv']:.3f} regime={rec['metrics']['phase_regime']}")
        else:
            log(f"[{name}] {i + 1}/{len(prompts)} ERROR {rec['error']}")
    return {"name": name, "records": records, "summary": summarize(records)}


def latency_bench(model: Any, tok: Any, prompt: str, states: Dict[str, Callable[[], Any]], cfg: Cfg,
                  log: Callable[[str], None]) -> Dict[str, Any]:
    """Interleaved fixed-token greedy latency benchmark. First entry of `states` is the baseline."""
    names = list(states)
    reps = int(cfg.latency_reps)
    n_tok = int(cfg.latency_tokens)
    series: Dict[str, List[Dict[str, Any]]] = {n: [] for n in names}
    for n in names:  # warm-up per state
        with states[n]():
            timed_generate(model, tok, prompt, cfg, seed=0, max_new_tokens=8, greedy=True, force_tokens=True)
    for r in range(reps):
        order = names[r % len(names):] + names[:r % len(names)]
        for n in order:
            with states[n]():
                g = timed_generate(model, tok, prompt, cfg, seed=0, max_new_tokens=n_tok, greedy=True, force_tokens=True)
            series[n].append({"rep": r, "wall_ms": g["wall_ms"], "n_new_tokens": g["n_new_tokens"], "ms_per_token": g["ms_per_token"]})
    base = names[0]
    out: Dict[str, Any] = {"prompt": prompt, "n_tokens_requested": n_tok, "reps": reps, "baseline": base, "states": {}}
    for n in names:
        mpt = [s["ms_per_token"] for s in series[n]]
        entry: Dict[str, Any] = {"series": series[n], "ms_per_token": _stats(mpt)}
        if n != base:
            diffs = [a["ms_per_token"] - b["ms_per_token"] for a, b in zip(series[n], series[base])]
            entry["overhead_ms_per_token_vs_base_paired"] = _stats(diffs)
            bm = float(np.mean([s["ms_per_token"] for s in series[base]]))
            entry["overhead_pct_vs_base"] = (100.0 * float(np.mean(diffs)) / bm) if bm > 0 else None
        out["states"][n] = entry
    log("[latency] " + ", ".join(f"{n}={out['states'][n]['ms_per_token']['mean']:.2f}ms/tok" for n in names))
    return out


def _probe_logits(model: Any, tok: Any, prompt: str, cfg: Cfg) -> Any:
    enc = tok(prompt, return_tensors="pt").to(cfg.device)
    with torch.no_grad():
        return model(**enc).logits[0, -1].float().cpu()



def section_atlas(P: Paper) -> str:
    s = f"{V10}/p30_atlas_diagnostics.json"
    lo = lambda m, k="accuracy": P.num(f"lowo_{m}_{k}", s, f"d['lowo'][{m!r}][{k!r}]", "{:.3f}")
    pa = lambda m, a: P.num(f"lowo_{m}_{a}", s, f"d['lowo'][{m!r}]['per_author'][{a!r}]", "{}")
    rows = [("3-mode GMM genome (Phase 26, quantile/scaled)", "gmm_quantile_scaled_phase26"),
            ("Fisher LDA on 24D style features", "fisher_z24"),
            ("Fisher LDA on 7 orthographic statistics", "fisher_ortho"),
            ("Fisher LDA on 24D + 7 orthographic", "fisher_z24_ortho"),
            ("Fisher LDA on 27 extended orthographic", "fisher_ortho_ext"),
            ("Fisher LDA on 24D + 27 extended orthographic (adopted)", "fisher_z24_ortho_ext")]
    t = "\n".join(f"| {name} | {lo(m)} | {lo(m, 'top3_accuracy')} | {pa(m, '001383')} | {pa(m, '001095')} |"
                  for name, m in rows)
    ab = "000879_vs_001383"
    ac = "000879_vs_000035"
    auc = lambda kind, pair, k: P.num(f"{kind}_{pair}_{k}", s, f"d[{kind!r}][{pair!r}][{k!r}]", "{:.3f}")
    n_works = P.num("atlas_n_works", s, "d['n_works']", "{}")
    chance = P.num("atlas_chance", s, "d['chance']", "{:.1f}")
    rs = f"{V10}/p30_reg_sensitivity.json"
    rmin = P.num("reg_sens_min", rs, "min(d.values())", "{:.3f}")
    rmax = P.num("reg_sens_max", rs, "max(d.values())", "{:.3f}")
    return f"""## 2. Measurement instrument on real text (Aozora Bunko atlas)
Corpus: {n_works} public-domain works by 10 authors (Aozora Bunko), 600-character windows with a 300-character
stride. Authors are labels of the atlas only; no author or character name enters any feature extractor.

**Leave-one-work-out (LOWO) author identification.** Each work is held out, the class model is refit on the
remaining works, and the held-out work is assigned to the nearest class (chance {chance}). The Fisher model uses
class-balanced within-class scatter, ridge 1e-2 fixed before evaluation (`fit_fisher`).

| Instrument | LOWO top-1 | LOWO top-3 | Tanizaki (hits/works) | Sakaguchi (hits/works) |
|---|---|---|---|---|
{t}

The plan's target (top-1 ≥ 0.70, and non-zero hits for Tanizaki and Sakaguchi) is not reached: the adopted model
reaches the value above, with one hit each for the two authors that previously had none. The ridge sensitivity
(`p30_reg_sensitivity.json`) gives top-1 between {rmin} and {rmax} for reg ∈ [1e-3, 1e-1]; the larger values are
not adopted because choosing reg after seeing LOWO accuracy would select on the evaluation.

**Window-level separability on real text** (Akutagawa A vs Tanizaki B, Akutagawa A vs Dazai C): ROC-AUC of the
instrument's score difference over 600-character windows of the two authors' works.

| Pair | ΔLL (GMM genome) AUC | Cohen's d | ΔF (Fisher) AUC | Cohen's d |
|---|---|---|---|---|
| A vs B | {auc('delta_ll_real_text', ab, 'window_auc_A_over_B')} | {auc('delta_ll_real_text', ab, 'window_cohen_d')} | {auc('delta_fisher_real_text', ab, 'window_auc_A_over_B')} | {auc('delta_fisher_real_text', ab, 'window_cohen_d')} |
| A vs C | {auc('delta_ll_real_text', ac, 'window_auc_A_over_B')} | {auc('delta_ll_real_text', ac, 'window_cohen_d')} | {auc('delta_fisher_real_text', ac, 'window_auc_A_over_B')} | {auc('delta_fisher_real_text', ac, 'window_cohen_d')} |

The GMM log-likelihood difference ΔLL used as the steering target in Phase 27 is a weak instrument on real text;
the Fisher score difference ΔF is used as the primary instrument from Phase 31 on.
"""


def section_p27(P: Paper) -> str:
    out = ["""## 3. Long-form generation with author steering (8B, ~2,000 characters per story)
### 3.1 Phase 27: genome steering through the GMM metric (negative result)
Two scripts × two seeds per model; ΔLL_AB = GMM log-likelihood(A) − (B) of the output, averaged over windows.

| Generator | new_ctrl ΔLL_AB | A-steered ΔLL_AB | B-steered ΔLL_AB |
|---|---|---|---|"""]
    for name, f in (("Qwen3-8B", "p27_q3_8b"), ("Qwen3-Swallow-8B", "p27_swallow_8b")):
        s = f"{V9}/{f}.json"
        out.append(f"| {name} | {P.num(f'{f}_ctrl', s, runs_mean('new_ctrl', 'delta_ll_AB'))} | "
                   f"{P.num(f'{f}_gA', s, runs_mean('gA_scaled', 'delta_ll_AB'))} | "
                   f"{P.num(f'{f}_gB', s, runs_mean('gB_scaled', 'delta_ll_AB'))} |")
    out.append("""
The A- and B-steered outputs did not separate in the intended direction. Two causes were identified afterwards:
the GMM instrument's low separability on real text (§2), and the style term being active only in the Climax
paragraph and the paragraph after it (`climax_only_steering`).
""")
    return "\n".join(out)


def p31_table(P: Paper, f: str, name: str) -> str:
    s = f"{V10}/{f}.json"
    rows = []
    for cond, label in (("new_ctrl", "new_ctrl"), ("gA", "A (Akutagawa)"), ("gB", "B (Tanizaki)"), ("gC", "C (Dazai)")):
        rows.append(f"| {label} | {P.num(f'{f}_{cond}_dF_AB', s, runs_mean(cond, 'delta_f_AB'))} | "
                    f"{P.num(f'{f}_{cond}_dF_AC', s, runs_mean(cond, 'delta_f_AC'))} | "
                    f"{P.num(f'{f}_{cond}_dLL_AB', s, runs_mean(cond, 'delta_ll_AB'))} | "
                    f"{P.num(f'{f}_{cond}_msl', s, runs_ortho_mean(cond, 0, exp=True), '{:.1f}')} | "
                    f"{P.num(f'{f}_{cond}_c100', s, runs_ortho_mean(cond, 2))} | "
                    f"{P.num(f'{f}_{cond}_coin', s, runs_sum(cond, 'coinages', length=True), '{}')} | "
                    f"{P.num(f'{f}_{cond}_unf', s, runs_sum(cond, 'unfinished_paragraphs'), '{}')} |")
    n = P.num(f"{f}_groups", s, n_groups(), "{}")
    pr = []
    for label, fld in (("ΔF_AB", "delta_f_AB"), ("ΔLL_AB", "delta_ll_AB"), ("commas / 100 chars", 2),
                       ("mean sentence length", 0)):
        key = fld if isinstance(fld, str) else f"o{fld}"
        pr.append(f"| {label} | {P.num(f'{f}_p_{key}_AB', s, paired('gA', 'gB', fld), '{}')} | "
                  f"{P.num(f'{f}_p_{key}_Actrl', s, paired('gA', 'new_ctrl', fld), '{}')} | "
                  f"{P.num(f'{f}_p_{key}_ctrlB', s, paired('new_ctrl', 'gB', fld), '{}')} |")
    gpu_sec = P.num(f"{f}_gen_sec", s, "d['generation_sec']", "{:.0f}")
    return (f"**{name}** (A100, {gpu_sec} s of generation for 24 stories). Condition means over {n} plot-seed groups:\n\n"
            "| Condition | ΔF_AB | ΔF_AC | ΔLL_AB | mean sentence length | commas / 100 chars | coinages | unfinished paragraphs |\n"
            "|---|---|---|---|---|---|---|---|\n" + "\n".join(rows) +
            f"\n\nPaired comparisons (number of the {n} groups in which the inequality holds):\n\n"
            "| Measure | A > B | A > new_ctrl | new_ctrl > B |\n|---|---|---|---|\n" + "\n".join(pr) + "\n")


def section_p31(P: Paper) -> str:
    out = ["""### 3.2 Phase 31: proposal derived from measured orthography + Fisher-direction particle weight
Two changes couple the author statistics to the decoder (Clause-level twisted SMC, 4 particles):
(i) the steady-rhythm band, comma target and kanji bias are derived from the author's measured orthographic
statistics, amplified around the atlas mean with κ = 2; (ii) a particle-weight term
γ⟨v̂_author, F(prefix + candidate) − μ̄⟩ in the Fisher space of §2, active in every paragraph.
The plan's literal bands (Tanizaki 42–115 characters with many commas) contradict the measured statistics
(Tanizaki writes slightly longer sentences with fewer commas than Akutagawa); the derived values were used.
Forbidden-word and calendar-year bans were added (soft logit penalty −15).
"""]
    for f, name in (("p31_q3_8b", "Qwen3-8B"), ("p31_swallow_8b", "Qwen3-Swallow-8B")):
        if P.has(f"{V10}/{f}.json"):
            out.append(p31_table(P, f, name))
    sb = f"{V10}/p31b_q3_8b.json"
    if P.has(sb):
        rows = []
        for cond, label in (("gA", "A (Akutagawa)"), ("gB", "B (Tanizaki)")):
            rows.append(f"| {label} | {P.num(f'p31b_{cond}_dF_AB', sb, runs_mean(cond, 'delta_f_AB'))} | "
                        f"{P.num(f'p31b_{cond}_dLL_AB', sb, runs_mean(cond, 'delta_ll_AB'))} | "
                        f"{P.num(f'p31b_{cond}_msl', sb, runs_ortho_mean(cond, 0, exp=True), '{:.1f}')} | "
                        f"{P.num(f'p31b_{cond}_c100', sb, runs_ortho_mean(cond, 2))} |")
        nm = P.num("p31b_merged_tokens", sb, "d['runs']['watch_gB_s3']['decoder_stats']['merged_period_tokens']", "{}")
        ab_len = P.num("p31b_len_AB", sb, "sum(1 for k, v in d['runs'].items() if v['condition']=='gA' and "
                                          "math.exp(v['ortho'][0]) > math.exp(d['runs'][k.replace('gA','gB')]['ortho'][0]))", "{}")
        out.append(f"""**Phase 31b (Qwen3-8B, A/B re-run).** The steady band held only the single-token "。"; the vocabulary has
{nm} further tokens containing a sentence end (e.g. merged "た。"), which bypassed the hold. Extending the hold to
them (steered conditions only; new_ctrl is unaffected):

| Condition | ΔF_AB | ΔLL_AB | mean sentence length | commas / 100 chars |
|---|---|---|---|---|
""" + "\n".join(rows) + f"""

Sentences of both steered conditions became longer than in 3.2 (compare the Qwen3-8B table), but A and B did not
separate in length (A longer than B in {ab_len} of 6 groups).
""")
    out.append("""Result. On the primary instrument ΔF_AB the intended order A > new_ctrl > B holds in every group for both
models, and the Dazai-steered condition lowers ΔF_AC. The comma rate moves in the Tanizaki direction in every
group but only partly in the Akutagawa direction (the control is already close to Akutagawa's measured rate).
Mean sentence length does not separate. The Swallow B-steered station stories contained kanji-numeral calendar
years in 3 of 3 seeds, i.e. the soft ban was insufficient there.
""")
    return "\n".join(out)


def section_judge(P: Paper) -> str:
    s = f"{V9}/p28j_cross.json"
    def pos(j: str) -> str:
        first = (f"(sum(1 for g in d['results'][{j!r}]['groups'].values() for m in g['matches'] for x in m['scores_ab'] if x>0)"
                 f"+sum(1 for g in d['results'][{j!r}]['groups'].values() for m in g['matches'] for x in m['scores_ba_as_a'] if x<0))")
        tot = (f"sum(1 for g in d['results'][{j!r}]['groups'].values() for m in g['matches'] "
               f"for x in m['scores_ab']+m['scores_ba_as_a'] if x!=0)")
        return P.num(f"p28j_posbias_{j}", s, f"{first}/{tot}", "{:.2f}")
    return f"""## 4. LLM-as-judge
### 4.1 Phase 28: generative pairwise judge (position-biased)
Cross-judging (Swallow judges Qwen3 outputs and vice versa), 5 axes, both presentation orders. The fraction of
axis decisions that chose the first-presented story was {pos('qwen3_8b')} (Swallow as judge) and {pos('swallow_8b')}
(Qwen3 as judge); the generative judge is therefore not usable as a measurement of condition differences.
""" + judge_p32(P)


def judge_p32(P: Paper) -> str:
    s = f"{V10}/p32j_cross.json"
    if not P.has(s):
        return ""
    def ms(j: str, a: str, b: str, fld: str) -> str:
        return (f"statistics.mean([m['full'][{fld!r}] for g in d['results'][{j!r}]['groups'].values() "
                f"for m in g['matches'] if m['a']=={a!r} and m['b']=={b!r}])")
    rows = []
    for j, name in (("qwen3_8b", "Qwen3 outputs, Swallow judge"), ("swallow_8b", "Swallow outputs, Qwen3 judge")):
        for a, b in (("new_ctrl", "min"), ("gA", "new_ctrl"), ("gB", "new_ctrl"), ("gC", "new_ctrl"), ("gA", "gB")):
            rows.append(f"| {name} | {a} vs {b} | {P.num(f'p32_{j}_{a}_{b}_pref', s, ms(j, a, b, 'preference'), '{:+.3f}')} | "
                        f"{P.num(f'p32_{j}_{a}_{b}_pb', s, ms(j, a, b, 'position_bias'), '{:.2f}')} |")
    mq = P.num("p32_mass_swallow_judge", s, "d['results']['qwen3_8b']['answer_mass_12']['mean']", "{:.3f}")
    mw = P.num("p32_mass_qwen3_judge", s, "d['results']['swallow_8b']['answer_mass_12']['mean']", "{:.3f}")
    return f"""
### 4.2 Phase 32: logit-debiased pairwise judge
One forward pass per order; the prompt ends with the answer stem and the judge's next-token log-probabilities of
"1" and "2" are read: s(A,B) = ln P(1) − ln P(2), preference = (s(A,B) − s(B,A))/2, position bias =
(s(A,B) + s(B,A))/2 (nats). A constant position bias cancels exactly; a content × position interaction does not.

| Setting | Pair (a vs b) | mean preference (whole text) | mean position bias |
|---|---|---|---|
""" + "\n".join(rows) + f"""

Probability mass on the two answer tokens: {mq} (Swallow judge) and {mw} (Qwen3 judge); the Qwen3 judge mostly
predicts other tokens at the answer position, so its values are unreliable. The position bias exceeds the
debiased preferences by roughly an order of magnitude, and the signs disagree between judges and between the
whole-text and paragraph-aligned modes. No quality difference between steered and unsteered stories is claimed.
"""


def section_phase_c(P: Paper) -> str:
    s = f"{V9}/p28c_q3_8b.json"
    dz = P.num("p28c_base_dz", s, "d['stages']['base']['summary']['deadzone']['count']", "{}")
    n = P.num("p28c_base_n", s, "d['stages']['base']['summary']['deadzone']['n']", "{}")
    return f"""## 5. Mid-layer steering and GRPO-LoRA (Phase C)
### 5.1 Phase 28: raw continuation prompts
Qwen3-8B (bf16, A100). With raw literary continuation prompts the base model was in the Deadzone in {dz} of {n}
outputs, so the former claim of "Deadzone escape" could not be tested on that set; steering at larger α increased
the Deadzone count, and the calibrated direction did not differ from a norm-matched random direction.
"""


def section_cleanroom(P: Paper) -> str:
    return """## 6. Clean-room gate
Tier S (128 bytes) and Tier M (4096 bytes) style binaries pass `threeRoomGate.ts`: no raw text retained and no
contiguous ≥ 7-character overlap with the source. These are fixture tests in the TypeScript suite and a repository
scan (`scripts/scan_cleanroom_copyright.py`); they show that the gate rejects the fixture violations, not a
generalisation rate on held-out data.
"""


def section_limitations(P: Paper) -> str:
    return """## 7. Limitations
- Small n: 6 plot-seed groups per model and condition, 46 works in the atlas. No significance testing.
- The style instrument (Fisher LDA) and the steering term share the same feature space; ΔF improvements are
  partly by construction. ΔLL (a different instrument) and orthographic statistics are reported for that reason.
- LOWO top-1 remains below 0.70.
- The 8B generative judge is position-biased; the logit-debiased judge cancels a constant position bias only.
- Coinage detection is a fixed regular-expression list, not a general detector.

## Appendix A. Synthetic self-consistency checks (not evidence)
The former Tables 1 and 4 remain reproducible from `python/usir_py/v2/benchmark_v2_large_scale.py` and
`benchmark_v3_english_cross_linguistic.py`. Their corpora are generated by the repository itself, with separability
calibrated by construction; they test that the pipeline runs end to end and are not evidence of real-world accuracy.
"""


SECTIONS = [section_abstract, section_retractions, section_atlas, section_p27, section_p31, section_judge,
            section_phase_c, section_cleanroom, section_limitations]


def main() -> None:
    P = Paper()
    body = "\n".join(fn(P) for fn in SECTIONS)
    for lit in FORBIDDEN:
        if lit in body:
            raise SystemExit(f"forbidden literal {lit!r} in generated paper")
    (ROOT / PAPER).write_text(body, encoding="utf-8")
    reg = {"paper_files": [PAPER], "forbidden": FORBIDDEN, "numbers": P.entries}
    REGISTRY.write_text(json.dumps(reg, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{PAPER}: {len(body)} chars, {len(P.entries)} registered numbers")


if __name__ == "__main__":
    main()

#!/usr/bin/env python
"""Phase 34: build usir_v4_paper.md from measured (non-mock) result JSONs only.

Every number printed in a results table is produced by `P.num(...)`, which evaluates a Python expression over the
loaded JSON and records a registry entry (id, file, text, source, expr, fmt) in scripts/paper_numbers.json.
`scripts/verify_paper_numbers.py` re-evaluates every entry independently and fails on any drift, on a mock source,
or on a retired mock literal.

Usage: python scripts/build_paper_v4.py
"""
from __future__ import annotations

import json
import math
import statistics
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[1]
PAPER = "usir_v4_paper.md"
REGISTRY = ROOT / "scripts" / "paper_numbers.json"
V9, V10 = "docs/handoff/v9", "docs/handoff/v10"

# literals of the retracted mock / synthetic tables (v2/v3 camera-ready papers); they must not reappear
FORBIDDEN = ["4.17 ms", "0.00 ms", "MAUVE 0.987", "0.745", "|β-1| 0.013", "100.0% escape",
             "Deadzone escape rate 100%", "ROC-AUC 0.934", "R² 0.851", "Δ² 41.28", "N=890"]

ENV = {"math": math, "statistics": statistics, "sum": sum, "len": len, "min": min, "max": max, "abs": abs,
       "round": round, "sorted": sorted}


class Paper:
    def __init__(self) -> None:
        self.entries: List[Dict[str, Any]] = []
        self.cache: Dict[str, Any] = {}
        self.ids: Dict[str, int] = {}

    def has(self, src: str) -> bool:
        return (ROOT / src).exists()

    def load(self, src: str) -> Any:
        if src not in self.cache:
            self.cache[src] = json.loads((ROOT / src).read_text(encoding="utf-8"))
        return self.cache[src]

    def num(self, nid: str, src: str, expr: str, fmt: str = "{:.2f}") -> str:
        val = eval(expr, {**ENV, "d": self.load(src)})  # noqa: S307 - expressions are written in this file
        s = fmt.format(val)
        n = self.ids.get(nid, 0)
        self.ids[nid] = n + 1
        self.entries.append({"id": nid if n == 0 else f"{nid}#{n}", "file": PAPER, "text": s, "source": src,
                             "expr": expr, "fmt": fmt})
        return s


def runs_mean(cond: str, field: str) -> str:
    return f"statistics.mean([v[{field!r}] for v in d['runs'].values() if v['condition']=={cond!r} and not v.get('error')])"


def runs_ortho_mean(cond: str, idx: int, exp: bool = False) -> str:
    inner = f"math.exp(v['ortho'][{idx}])" if exp else f"v['ortho'][{idx}]"
    return f"statistics.mean([{inner} for v in d['runs'].values() if v['condition']=={cond!r} and not v.get('error')])"


def runs_sum(cond: str, field: str, length: bool = False) -> str:
    inner = f"len(v[{field!r}])" if length else f"v[{field!r}]"
    return f"sum({inner} for v in d['runs'].values() if v['condition']=={cond!r} and not v.get('error'))"


def paired(c1: str, c2: str, field: str, base: str = "new_ctrl") -> str:
    """number of (plot, seed) groups where condition c1 > c2 on `field` (ortho index when field is an int)."""
    def get(c: str) -> str:
        key = f"d['runs'][k.replace({base!r}, {c!r})]"
        return f"{key}['ortho'][{field}]" if isinstance(field, int) else f"{key}[{field!r}]"
    return f"sum(1 for k, v in d['runs'].items() if v['condition']=={base!r} and {get(c1)} > {get(c2)})"


def n_groups(base: str = "new_ctrl") -> str:
    return f"sum(1 for v in d['runs'].values() if v['condition']=={base!r})"



#!/usr/bin/env python
"""Phase 18 M18.2: calibrate the article / cot_reasoning QDA profiles from real text.

Data:
  article       : Aozora essays / criticism / lectures in data/aozora_manifest.json (genre "article"),
                  cached by scripts/fetch_aozora.py into data/aozora_cache/.
  cot_reasoning : 40 Japanese chain-of-thought answers generated by Qwen2.5-3B-Instruct on Colab
                  (artifacts/qda_calibration/colab_gen_cot_corpus.json, scripts/colab_gen_cot_corpus.py).

Rule (deterministic, recorded in the output):
  - chunks: same sentence-aligned 160-440 char chunks as the novel calibration (measure_qda_domain.chunk_text);
    a cot answer shorter than 160 chars is used whole if it has >= 80 chars.
  - work balance: at most CAP chunks per work (evenly spaced), so one long work cannot dominate.
  - sigma_crit_low / sigma_crit_high = q05 / q95 of ||p||_2 (90% central band), rounded to 2 decimals.
  - shock_mean_max = q95 of the Shock-group mean q[3,7,11], rounded to 2 decimals.
  - mu_crit = per-dimension median of z = (q, p) (24-D), rounded to 3 decimals.

Usage: cd python && uv run python ../scripts/calibrate_qda_domains.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))
sys.path.insert(0, str(ROOT / "scripts"))

from usir_py.extractor_24d import extract_usir_24d  # noqa: E402
from measure_qda_domain import chunk_text  # noqa: E402
from fetch_aozora import load_manifest_texts  # noqa: E402

CAP = 60


def _balanced(chunks: list[str], cap: int = CAP) -> list[str]:
    if len(chunks) <= cap:
        return chunks
    idx = np.linspace(0, len(chunks) - 1, cap).round().astype(int)
    return [chunks[i] for i in sorted(set(idx.tolist()))]


def _features(units: list[tuple[str, list[str]]]) -> dict:
    qs, pn, sh, per_work = [], [], [], {}
    for work, chunks in units:
        for ch in chunks:
            ext = extract_usir_24d(ch)
            q = np.asarray(ext["q"], dtype=float)
            p = np.asarray(ext["p"], dtype=float)
            qs.append(np.concatenate([q, p]))
            pn.append(float(np.linalg.norm(p)))
            sh.append(float(np.mean([q[3], q[7], q[11]])))
        per_work[work] = len(chunks)
    qs_a = np.asarray(qs)
    pn_a, sh_a = np.asarray(pn), np.asarray(sh)
    qt = lambda a: {k: round(float(np.quantile(a, v)), 4) for k, v in  # noqa: E731
                    [("min", 0), ("q05", .05), ("q25", .25), ("median", .5), ("q75", .75), ("q95", .95), ("max", 1)]}
    return {
        "n_chunks": int(pn_a.size),
        "chunks_per_work": per_work,
        "p_norm": qt(pn_a),
        "shock_mean": qt(sh_a),
        "calibrated": {
            "sigma_crit_low": round(float(np.quantile(pn_a, 0.05)), 2),
            "sigma_crit_high": round(float(np.quantile(pn_a, 0.95)), 2),
            "shock_mean_max": round(float(np.quantile(sh_a, 0.95)), 2),
            "mu_crit": [round(float(v), 3) for v in np.median(qs_a, axis=0)],
        },
    }


def main() -> None:
    art = [(f"{e['author_id']}:{e['title']}", _balanced(chunk_text(e["text"]))) for e in load_manifest_texts("article")]
    cot_src = json.loads((ROOT / "artifacts/qda_calibration/colab_gen_cot_corpus.json").read_text(encoding="utf-8"))
    cot = []
    for i, t in enumerate(cot_src["outputs"]):
        t = t.replace("\n", "")
        ch = chunk_text(t) or ([t] if len(t) >= 80 else [])
        cot.append((f"cot_{i:02d}", ch))
    res = {
        "rule": "low/high = q05/q95 of ||p||_2; shock_mean_max = q95 of mean q[3,7,11]; mu = median (q, p); "
                f"<= {CAP} evenly spaced chunks per work",
        "article": _features(art),
        "cot_reasoning": {**_features(cot), "source": {k: cot_src[k] for k in ("model", "decoding")}},
    }
    out = ROOT / "artifacts/qda_calibration/qda_domain_calibration.json"
    out.write_text(json.dumps(res, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    for d in ("article", "cot_reasoning"):
        r = res[d]
        print(d, r["n_chunks"], "p", r["p_norm"], "shock", r["shock_mean"])
        print("  ->", r["calibrated"])


if __name__ == "__main__":
    main()
